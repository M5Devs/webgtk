#!/usr/bin/env bash
# SPDX-License-Identifier: LGPL-2.1-or-later
#
# Compile-verify src/backend_chromium.cc against a prepared engine tree.
#
# The pruned archive cannot link a working engine, but it can compile the one
# translation unit that talks to Content, as long as the generated headers that
# unit needs exist. This script:
#
#   1. generates every buildflag header (one ninja invocation);
#   2. extracts the exact flags gn emits for a //content source file, via
#      scripts/engine_compile_flags.py;
#   3. compiles src/backend_chromium.cc, asking ninja for each generated header
#      it still misses until the compile is clean.
#
# It exits 0 only when clang reports no error and no warning, so API drift in
# the Content/Blink/Skia calls fails the run.
#
# Usage:
#   scripts/verify_engine.sh [--dir <engine-root>] [--out <work-dir>]
#
# --dir defaults to $WEBGTK_ENGINE_DIR or <repo>/engine. --out defaults to a
# fresh temporary directory; pass one to keep the generated script and object.
# The engine tree must already have been generated by scripts/setup_engine.sh.

set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENGINE_DIR="${WEBGTK_ENGINE_DIR:-$REPO_ROOT/engine}"
WORK=""

while [ $# -gt 0 ]; do
  case "$1" in
    --dir) ENGINE_DIR="$2"; shift 2 ;;
    --out) WORK="$2"; shift 2 ;;
    -h|--help) sed -n '2,22p' "$0"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

SRC_DIR="$ENGINE_DIR/chromium"
GN_OUT="$SRC_DIR/out/webgtk"
NINJA="${NINJA:-ninja}"
SOURCE="$REPO_ROOT/src/backend_chromium.cc"

log() { printf '\n==> %s\n' "$*"; }

if ! command -v "$NINJA" >/dev/null 2>&1; then
  echo "error: ninja not found on PATH" >&2
  exit 2
fi
if [ ! -f "$GN_OUT/build.ninja" ]; then
  echo "error: no gn output at $GN_OUT; run scripts/setup_engine.sh first" >&2
  exit 2
fi
if [ -z "$WORK" ]; then
  WORK="$(mktemp -d)"
fi
mkdir -p "$WORK"

# ------------------------------------------------ generated buildflag headers
# gn writes these from a small script; without them every Chromium header that
# does #include "base/.../buildflags.h" fails immediately.
log "Generating buildflag headers"
"$NINJA" -C "$GN_OUT" -t targets all 2>/dev/null \
  | grep -oE 'gen/[A-Za-z0-9_/.]+buildflags\.h' | sort -u > "$WORK/buildflags.txt"
if [ -s "$WORK/buildflags.txt" ]; then
  # shellcheck disable=SC2046
  if ! "$NINJA" -C "$GN_OUT" $(cat "$WORK/buildflags.txt") > "$WORK/buildflags.log" 2>&1; then
    echo "error: could not generate buildflag headers" >&2
    tail -20 "$WORK/buildflags.log" >&2
    exit 1
  fi
fi

# ------------------------------------------------------------- compile command
# gn emits include paths relative to the output directory (-I../.. -Igen), so
# the generated script must run from $GN_OUT; engine_compile_flags.py writes
# that cd into the script.
log "Extracting the //content compile command"
CMD_OBJ="obj/content/public/app/app/content_main_delegate.o"
"$NINJA" -C "$GN_OUT" -t commands "$CMD_OBJ" 2>/dev/null \
  | grep -E 'clang\+\+.* -c ' | tail -1 > "$WORK/cmd.txt"
if [ ! -s "$WORK/cmd.txt" ]; then
  echo "error: no clang++ command found for $CMD_OBJ" >&2
  exit 1
fi

python3 "$REPO_ROOT/scripts/engine_compile_flags.py" \
  --cmd "$WORK/cmd.txt" --repo "$REPO_ROOT" \
  --source "$SOURCE" --object "$WORK/backend_chromium.o" \
  --script "$WORK/cc.sh" --cwd "$GN_OUT"

# ----------------------------------------------------------- compile and retry
log "Compiling $SOURCE"
built=""
for round in $(seq 1 400); do
  if "$WORK/cc.sh" 2> "$WORK/err.txt"; then
    log "OK: $SOURCE compiles cleanly against $SRC_DIR"
    echo "  object: $WORK/backend_chromium.o"
    echo "  rounds: $round"
    exit 0
  fi
  hdr="$(grep -oE "fatal error: '[^']+' file not found" "$WORK/err.txt" \
         | head -1 | sed "s/fatal error: '\(.*\)' file not found/\1/")"
  if [ -z "$hdr" ]; then
    echo "error: compile failed" >&2
    grep -E "error:" "$WORK/err.txt" | head -40 >&2
    exit 1
  fi
  case " $built " in
    *" $hdr "*)
      echo "error: ninja cannot provide $hdr" >&2
      grep -E "error:" "$WORK/err.txt" | head -20 >&2
      exit 1
      ;;
  esac
  built="$built $hdr"
  if "$NINJA" -C "$GN_OUT" "gen/$hdr" > "$WORK/gen.log" 2>&1; then
    echo "  generated gen/$hdr"
  else
    echo "  ninja could not generate gen/$hdr" >&2
  fi
done

echo "error: gave up after too many rounds" >&2
exit 1
