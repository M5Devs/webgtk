#
# Recreate the GN files the pruned engine archive is missing, so that a local
# `gn gen` completes.
#
# The WebGTK engine archive is pruned for size; `gn gen` aborts at the first
# import it cannot resolve. Every stub written here stands in for a file the
# full Chromium checkout has but the archive dropped. Most belong to trees
# WebGTK never builds (iOS, Android, Fuchsia, Chrome, Cast, Remoting,
# DevTools), yet GN still loads them because a BUILD.gn it *does* need imports
# them at parse time.
#
# Usage: scripts/patch_gn_stubs.sh [engine-root]
#        (engine-root defaults to $WEBGTK_ENGINE_ROOT, then ./engine/chromium)
#
# Re-running is safe: every file is (over)written with the same contents.
set -uo pipefail

S=${1:-${WEBGTK_ENGINE_ROOT:-engine/chromium}}
if [ ! -f "$S/.gn" ]; then
  echo "error: $S does not look like a Chromium source root (no .gn)" >&2
  echo "usage: $0 [engine-root]" >&2
  exit 2
fi

# stub <relative-path>; the file body is read from stdin.
stub() {
  local path="$S/$1"
  mkdir -p "$(dirname "$path")"
  cat > "$path"
}

# flags <relative-path> <comment> <flag>...
# Writes a .gni declaring each named build flag with value false. This is the
# shape most missing files need: the pruned feature is simply off.
flags() {
  local path="$1" comment="$2"
  shift 2
  {
    echo "# $comment"
    echo "#"
    echo "# Generated by scripts/patch_gn_stubs.sh for the pruned engine archive."
    echo "declare_args() {"
    for flag in "$@"; do
      echo "  $flag = false"
    done
    echo "}"
  } > "$S/$path"
}

# empty_gni <relative-path> <comment>
empty_gni() {
  local path="$1" comment="$2"
  {
    echo "# $comment"
    echo "#"
    echo "# Generated by scripts/patch_gn_stubs.sh for the pruned engine archive."
  } > "$S/$path"
}

# --------------------------------------------------------------------------
# Generated files the archive never ships.
# --------------------------------------------------------------------------
stub build/config/gclient_args.gni <<'EOF'
# Generated file. Do not edit.
#
# Restored by scripts/patch_gn_stubs.sh: the archive ships neither the gclient
# checkout metadata nor this generated file, and //build/config/BUILDCONFIG.gn
# imports it unconditionally. These are the values a plain Linux checkout with
# no optional checkouts would have.
build_with_chromium = true
checkout_android = false
checkout_clang_coverage_tools = false
checkout_copybara = false
checkout_fuchsia = false
checkout_glic_e2e_tests = false
checkout_ios_webkit = false
checkout_mutter = false
checkout_openxr = false
checkout_src_internal = false
checkout_src_internal_infra = false
checkout_clusterfuzz_data = false
android_ndk_version = "2@30.0.16248370"
cros_boards = ""
cros_boards_with_qemu_images = ""
generate_location_tags = false
EOF

# --------------------------------------------------------------------------
# //testing — imported by //media and //content.
# --------------------------------------------------------------------------
stub testing/libfuzzer/fuzzer_test.gni <<'EOF'
# Minimal stand-in for //testing/libfuzzer/fuzzer_test.gni.
#
# The import is load-bearing twice over: //media/media_options.gni reads
# is_asan/is_tsan through the sanitizers import, and BUILD.gn files that call
# test() (for example //services/webnn) see it only because the real file
# re-exports it from //testing/test.gni.
import("//build/config/sanitizers/sanitizers.gni")
import("//testing/test.gni")

# The real template builds a libFuzzer executable against
# //testing/libfuzzer:libfuzzer_main, which the pruned tree does not carry.
# WebGTK never builds fuzz targets, so the template expands to an inert
# source_set: the name stays resolvable and no fuzzing runtime is pulled in.
# not_needed() accepts every argument the invokers pass (sources, deps, dict,
# seed_corpus, ...) without forwarding any of them.
import("//build/config/sanitizers/sanitizers.gni")

template("fuzzer_test") {
  not_needed(invoker, "*")
  source_set(target_name) {
  }
}

# Invokers do `configs += [...]`, which needs configs in scope before the
# template body runs; the real file seeds configs through set_defaults too.
set_defaults("fuzzer_test") {
  configs = default_executable_configs
}
EOF

stub testing/test.gni <<'EOF'
# Minimal stand-in for //testing/test.gni.
#
# The real file pulls in a long list of config gnis; the two that downstream
# BUILD.gn files depend on transitively are sanitizers (is_asan/is_tsan) and
# rust_static_library (url/BUILD.gn declares rust_static_library targets and
# reaches the template only through this import).
import("//build/config/sanitizers/sanitizers.gni")
import("//build/rust/rust_static_library.gni")

# Several BUILD.gn files reference this in visibility lists; the real file
# defines it as "" on desktop and a suffix on Android.
exec_target_suffix = ""

# The real template builds a test executable plus a runner. The archive ships
# neither gtest nor the test sources, and WebGTK builds no test targets, so both
# templates expand to an inert source_set. not_needed() accepts every argument
# the invokers pass (sources, deps, configs, use_xvfb, ...) without forwarding
# any of them.
template("test") {
  not_needed(invoker, "*")
  source_set(target_name) {
  }
}

template("test_runner") {
  not_needed(invoker, "*")
  source_set(target_name) {
  }
}

# Invokers do `configs += [...]`; the real file seeds configs the same way.
set_defaults("test") {
  configs = default_executable_configs
}

set_defaults("test_runner") {
  configs = default_executable_configs
}
EOF

echo "patched GN stubs in $S"
